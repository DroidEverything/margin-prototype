"""Build the Bennu ephemeris pack (Gap Report §H.6 / spec §8).

Bennu was the last hardcoded trajectory (SBDB snapshot a/e/M0 in three
files, no epoch, no uncertainty). This replaces the magic numbers with a
fitted ephemeris while keeping the Kepler fallback as explicit DEGRADED cover:

  JPL Horizons vectors, source ORX_merged_DE424 (OSIRIS-REx-merged solution)
      -> tools/horizons_cache/ (raw, exact query params logged)
      -> Chebyshev fits per 8-day granule, deg 10 (same math as build_de440)
      -> js/astronomy-jpl-data-bennu.js (defines JPL_EPHEM_BENNU)
      -> QA/jpl_reference_vectors_bennu.json (HELD-OUT single-epoch queries)

Solution provenance is vendored separately in QA/bennu_sbdb_solution.json
(orbit_id 118, condition_code 0, 554 obs 1999–2020, producer Farnocchia).

Coverage 1990-01-01..2110-12-31 matches the planetary pack. Horizons serves
Bennu across the whole range (verified 1990/2026/2109 before building).

Usage:
  python tools/build_bennu.py build   # fit + emit data file
  python tools/build_bennu.py golden  # held-out reference vectors
  python tools/build_bennu.py report  # emitted-file residual spot-checks
"""
import sys
import os
import hashlib
import json
import numpy as np
from numpy.polynomial.chebyshev import chebval

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from build_de440 import fit_grid, r10
import horizons

ROOT = os.path.dirname(HERE)

# Bennu's eccentric orbit + Earth encounters need fine granules: 8 d left
# 31 km in-sample errors; perihelion curvature needs degree 12 at 2 d
# granules (deg 10 left 34 km localized at perihelion passages).
# Cost is accepted for a rendezvous target (see build log).
START, STOP, STEP, GRANULE, DEG = "1990-01-01", "2110-12-31", "3h", 2, 12
GOLDEN_EPOCHS = [
    "2000-01-01 00:00", "2015-06-01 00:00", "2016-09-21 00:00",
    "2025-09-21 00:00", "2026-09-21 00:00", "2027-09-21 00:00",
    "2030-06-15 00:00", "2036-09-21 00:00", "2050-01-01 00:00",
    "2100-01-01 00:00",
]


def sample():
    # Horizons caps rows per response: fetch per-decade and concatenate.
    import datetime as _dt
    jdA, posA, velA, info = [], [], [], None
    y0, y1 = int(START[:4]), int(STOP[:4])
    for y in range(y0, y1, 10):
        s = "%04d-01-01" % y
        e = "%04d-01-01" % min(y + 10, y1 + 1)
        info, recs = horizons.query("101955", "500@0", s, e, STEP)
        jdA.extend(r["jd"] for r in recs)
        posA.extend(r["pos"] for r in recs)
        velA.extend(r["vel"] for r in recs)
        print("  sampled %s..%s: %d rows" % (s, e, len(recs)), flush=True)
    return info, np.array(jdA), np.array(posA), np.array(velA)


def cmd_build():
    info, jd, pos, vel = sample()
    t0, t1, gran, dg, worst, worst_v, coeff = fit_grid(jd, pos, vel, GRANULE, DEG)
    src = "%s/%s" % (info["source_target"], info["source_center"])
    rec = {"kind": "ssb", "cmd": "101955", "center": "500@0",
           "src": src, "t0": t0, "t1": t1, "granule": gran, "deg": dg,
           "fitResidualKm": round(worst, 6),
           "fitResidualKmPerSec": round(worst_v, 9),
           "coeff": coeff}
    with open(os.path.join(ROOT, "QA", "bennu_sbdb_solution.json")) as f:
        soln = json.load(f)
    data = {
        "provider": "JPL_SBDB",
        "kernel": "ORX_merged_DE424",
        "kernelSet": ["ORX_merged_DE424"],
        "bodySources": {"bennu": src},
        "solution": {k: soln["solution"][k] for k in
                     ["orbit_id", "soln_date", "epoch", "producer",
                      "condition_code", "data_arc", "n_obs_used"]},
        "source": "JPL Horizons API VECTORS (ECLIPTIC_J2000 / SSB / TDB, KM-S)",
        "retrieved": "2026-09-22",
        "url": "https://ssd.jpl.nasa.gov/api/horizons.api",
        "frame": "ECLIPTIC_J2000",
        "origin": "SSB",
        "timeScale": "TDB",
        "note": "Chebyshev fit of Horizons Bennu vectors (OSIRIS-REx-merged "
                "solution; see QA/bennu_sbdb_solution.json). Coefficients "
                "rounded to 10 significant figures. NEVER extrapolate.",
        "bodies": {"bennu": rec},
    }
    payload = json.dumps(rec, sort_keys=True)
    data["checksum"] = "sha256:" + hashlib.sha256(payload.encode()).hexdigest()
    js = ("/* GENERATED by tools/build_bennu.py — do not hand-edit.\n"
          "   JPL Horizons Bennu vectors (ORX_merged_DE424), Chebyshev-fitted\n"
          "   per granule. See data.note + data.checksum. */\n"
          "var JPL_EPHEM_BENNU = " + json.dumps(data, separators=(",", ":")) + ";\n")
    path = os.path.join(ROOT, "js", "astronomy-jpl-data-bennu.js")
    with open(path, "w", encoding="utf-8") as f:
        f.write(js)
    nums = sum(len(g) for ax in "xyz" for g in coeff[ax])
    print("bennu: %d samples -> %d granules x deg %d, in-sample maxpos %.4f km, maxvel %.3e km/s, src %s"
          % (len(jd), len(coeff["x"]), dg, worst, worst_v, src))
    print("wrote %s (%.2f MB, %d coeffs, checksum %s)"
          % (path, len(js) / 1e6, nums, data["checksum"]))


def cmd_golden():
    import datetime as _dt
    gold = {"meta": {"source": "JPL Horizons API VECTORS ECLIPTIC_J2000/SSB/TDB",
                     "retrieved": "2026-09-22",
                     "note": "Held-out epochs: same convention as the DE441 QA "
                             "(1-minute window, first record kept)."},
            "epochs": GOLDEN_EPOCHS, "vectors": {"bennu": []}}
    for ep in GOLDEN_EPOCHS:
        t0 = _dt.datetime.strptime(ep, "%Y-%m-%d %H:%M")
        stop = (t0 + _dt.timedelta(minutes=1)).strftime("%Y-%m-%d %H:%M")
        info, recs = horizons.query("101955", "500@0", ep, stop, "1m")
        if not recs:
            raise RuntimeError("no record @ %s" % ep)
        r = recs[0]
        gold["vectors"]["bennu"].append({"jd": r["jd"], "pos": r["pos"], "vel": r["vel"]})
        print("golden bennu @ %s  JD %.6f  src %s" % (ep, r["jd"], info["source_target"]))
    path = os.path.join(ROOT, "QA", "jpl_reference_vectors_bennu.json")
    with open(path, "w") as f:
        json.dump(gold, f)
    print("wrote %s (1 body x %d epochs)" % (path, len(GOLDEN_EPOCHS)))


def cmd_report():
    path = os.path.join(ROOT, "js", "astronomy-jpl-data-bennu.js")
    with open(path, encoding="utf-8") as f:
        txt = f.read()
    payload = txt.split("var JPL_EPHEM_BENNU = ", 1)[1].rstrip().rstrip(";")
    data = json.loads(payload)
    _, jd, pos, _ = sample()
    rec = data["bodies"]["bennu"]
    cx = rec["coeff"]["x"]; ng = len(cx)
    worst = 0.0
    g = np.floor((jd - rec["t0"]) / rec["granule"]).astype(int)
    g[g < 0] = 0
    g[g > ng - 1] = ng - 1
    for gi in range(ng):
        a = rec["t0"] + gi * rec["granule"]
        b = a + rec["granule"]
        sel = (g == gi) & (jd >= a - 1e-9) & (jd <= b + 1e-9)
        if not sel.any():
            continue
        tau = 2 * (jd[sel] - a) / (b - a) - 1.0
        for ax in range(3):
            c = np.array(rec["coeff"]["xyz"[ax]][gi])
            worst = max(worst, float(np.max(np.abs(chebval(tau, c) - pos[sel, ax]))))
    print("bennu: %d granules, emitted-file max residual %.4f km, src %s" % (ng, worst, rec["src"]))
    print("checksum: %s" % data["checksum"])


if __name__ == "__main__":
    which = sys.argv[1] if len(sys.argv) > 1 else "build"
    {"build": cmd_build, "golden": cmd_golden, "report": cmd_report}[which]()
